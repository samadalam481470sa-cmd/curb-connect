const BY_CODE = new Map(ENTERPRISE_WORK_PACKAGES.map((pkg) => [pkg.code, pkg]));

export function findWorkPackage(code: string): EnterpriseWorkPackage | undefined {
  return BY_CODE.get(code);
}

export function workPackageFieldKey(label: string): string {
  return label
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
}

export function workPackageFieldKeys(pkg: EnterpriseWorkPackage): string[] {
  return pkg.fields.map(workPackageFieldKey);
}

export function isWorkPackageStatus(pkg: EnterpriseWorkPackage, status: string): boolean {
  return pkg.lifecycle.includes(status);
}

export function nextLifecycleStage(pkg: EnterpriseWorkPackage, current: string): string | null {
  const index = pkg.lifecycle.indexOf(current);
  if (index < 0 || index >= pkg.lifecycle.length - 1) return null;
  return pkg.lifecycle[index + 1] ?? null;
}

export function workPackageLabel(status: string): string {
  return status.replaceAll('_', ' ');
}

export function domainLabel(key: EnterpriseDomainKey): string {
  return ENTERPRISE_DOMAINS.find((domain) => domain.key === key)?.label ?? key;
}

export function workPackagesForDomain(key: EnterpriseDomainKey): EnterpriseWorkPackage[] {
  return ENTERPRISE_WORK_PACKAGES.filter((pkg) => pkg.domain === key);
}
