export type EnterpriseReleaseGate = 1 | 2 | 3 | 4;
export type EnterpriseSpecification = 'core' | 'expansion' | 'indexed';

export interface EnterpriseWorkPackage {
  readonly code: string;
  readonly key: string;
  readonly title: string;
  readonly domain: EnterpriseDomainKey;
  readonly owner: string;
  /** Suggested gate from the blueprint's delivery sequence; a planning aid, not a claim. */
  readonly gate: EnterpriseReleaseGate;
  readonly specification: EnterpriseSpecification;
  readonly fields: readonly string[];
  readonly actions: readonly string[];
  readonly lifecycle: readonly string[];
  readonly exception: string;
  readonly tables: readonly string[];
}

type Args = [
  code: string,
  key: string,
  title: string,
  domain: EnterpriseDomainKey,
  owner: string,
  gate: EnterpriseReleaseGate,
  specification: EnterpriseSpecification,
  fields: readonly string[],
  actions: readonly string[],
  lifecycle: readonly string[],
  exception: string,
  tables: readonly string[],
];

function wp(...args: Args): EnterpriseWorkPackage {
  const [
    code,
    key,
    title,
    domain,
    owner,
    gate,
    specification,
    fields,
    actions,
    lifecycle,
    exception,
    tables,
  ] = args;
  return {
    code,
    key,
    title,
    domain,
    owner,
    gate,
    specification,
    fields,
    actions,
    lifecycle,
    exception,
    tables,
  };
}

