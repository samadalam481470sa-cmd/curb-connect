#!/usr/bin/env node
// Builds docs/traceability.md from docs/requirements/blueprint.yaml (+ optional evidence.yaml).
// Usage: node scripts/traceability/generate.mjs [--check]
//   --check  validate only (no write); exits 1 if any epic lacks a valid status, IDs are duplicated,
//            the epic count is not 100, or evidence references unknown tickets / invalid statuses.
// Dependency-free on purpose (STR-001-DOC): runs with plain `node`.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseYaml } from './yaml-lite.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const reqDir = join(root, 'docs', 'requirements');
const outFile = join(root, 'docs', 'traceability.md');
const check = process.argv.includes('--check');

const STATUSES = [
  'planned',
  'in_progress',
  'implemented',
  'partial',
  'blocked_vendor',
  'blocked_owner',
  'process_doc',
];
const EXPECTED_EPICS = 100;
const errors = [];
const warnings = [];

const blueprint = parseYaml(readFileSync(join(reqDir, 'blueprint.yaml'), 'utf8'));
const epics = Array.isArray(blueprint?.epics) ? blueprint.epics : [];
const evidencePath = join(reqDir, 'evidence.yaml');
const evidence = existsSync(evidencePath)
  ? (parseYaml(readFileSync(evidencePath, 'utf8'))?.tickets ?? {})
  : {};

if (epics.length !== EXPECTED_EPICS)
  errors.push(`expected ${EXPECTED_EPICS} epics, found ${epics.length}`);
const seen = new Set();
const allTickets = new Set();
for (const e of epics) {
  if (!e?.id) {
    errors.push(`epic on page ${e?.page ?? '?'} has no id`);
    continue;
  }
  if (seen.has(e.id)) errors.push(`duplicate epic id ${e.id}`);
  seen.add(e.id);
  if (!e.status) errors.push(`${e.id} has no status`);
  else if (!STATUSES.includes(e.status)) errors.push(`${e.id} has invalid status "${e.status}"`);
  for (const k of ['title', 'chapter', 'release', 'slice', 'priority'])
    if (!e[k]) errors.push(`${e.id} missing ${k}`);
  for (const t of e.tickets ?? []) allTickets.add(t);
}
for (const [ticket, ev] of Object.entries(evidence)) {
  if (!allTickets.has(ticket)) errors.push(`evidence for unknown ticket ${ticket}`);
  if (!ev || !STATUSES.includes(ev.status))
    errors.push(`evidence ${ticket} has invalid status "${ev?.status}"`);
  for (const f of [...(ev?.files ?? []), ...(ev?.tests ?? [])]) {
    if (!existsSync(join(root, f))) warnings.push(`evidence ${ticket}: file not found: ${f}`);
  }
}

// Epic status: the blueprint status unless ticket evidence exists, then an aggregate of ticket statuses.
function epicStatus(e) {
  const evs = (e.tickets ?? []).map((t) => evidence[t]).filter(Boolean);
  if (evs.length === 0) return e.status;
  const sts = (e.tickets ?? []).map((t) => evidence[t]?.status ?? 'planned');
  for (const b of ['blocked_owner', 'blocked_vendor']) if (sts.includes(b)) return b;
  const done = (s) => s === 'implemented' || s === 'process_doc';
  if (sts.every(done)) return sts.every((s) => s === 'process_doc') ? 'process_doc' : 'implemented';
  if (sts.some((s) => done(s) || s === 'partial')) return 'partial';
  if (sts.some((s) => s === 'in_progress')) return 'in_progress';
  return 'planned';
}

for (const w of warnings) console.warn(`warning: ${w}`);
if (errors.length) {
  for (const er of errors) console.error(`error: ${er}`);
  process.exit(1);
}
if (check) {
  console.log(
    `traceability check passed: ${epics.length} epics, ${Object.keys(evidence).length} evidence entries`,
  );
  process.exit(0);
}

const cell = (s) =>
  String(s ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');
const link = (p) => `[${p}](${relative(join(root, 'docs'), join(root, p)).replace(/\\/g, '/')})`;
const chapters = [...new Set(epics.map((e) => e.chapter))];
const rows = epics.map((e) => ({ ...e, computed: epicStatus(e) }));
let md = '# Traceability matrix\n\n';
md +=
  '<!-- GENERATED by scripts/traceability/generate.mjs from docs/requirements/blueprint.yaml and evidence.yaml. Do not edit by hand; run `npm run traceability`. -->\n\n';
md += `Epics: ${rows.length}. Status vocabulary: ${STATUSES.join(', ')}.\n\n## Summary\n\n`;
const count = (f) => STATUSES.map((s) => rows.filter((r) => f(r) && r.computed === s).length);
md += `| Group | Total | ${STATUSES.join(' | ')} |\n|---|---|${STATUSES.map(() => '---').join('|')}|\n`;
const groups = [
  ...chapters.map((c) => [c, (r) => r.chapter === c]),
  ...['MVP', 'V1', 'V2'].map((rel) => [`Release ${rel}`, (r) => r.release === rel]),
  ...[...new Set(rows.map((r) => r.slice))].map((s) => [`Slice ${s}`, (r) => r.slice === s]),
  ['**All**', () => true],
];
for (const [name, f] of groups)
  md += `| ${name} | ${rows.filter(f).length} | ${count(f).join(' | ')} |\n`;
for (const c of chapters) {
  md += `\n## ${c}\n\n| ID | Title | Prio | Release | Slice | Status | Tickets / evidence | Blockers |\n|---|---|---|---|---|---|---|---|\n`;
  for (const r of rows.filter((x) => x.chapter === c)) {
    const ev = (r.tickets ?? [])
      .map((t) => {
        const v = evidence[t];
        if (!v) return t;
        const links = [...(v.files ?? []), ...(v.tests ?? [])].map(link).join(', ');
        return `${t} (${v.status}${links ? ': ' + links : ''}${v.notes ? '; ' + v.notes : ''})`;
      })
      .join('<br>');
    md += `| ${r.id} | ${cell(r.title)} | ${r.priority} | ${r.release} | ${r.slice} | ${r.computed} | ${cell(ev)} | ${cell((r.dependencies ?? []).join(', ') || '-')} |\n`;
  }
}
writeFileSync(outFile, md);
console.log(`wrote ${relative(root, outFile)}: ${rows.length} epics`);
